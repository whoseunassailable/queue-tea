const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec']
const dayText = (day: string) => `${Number(day.slice(8, 10))} ${MONTHS[Number(day.slice(5, 7)) - 1] ?? ''}`
const weekRange = (first: string, last: string) => (first.slice(5, 7) === last.slice(5, 7) ? `${Number(first.slice(8, 10))} – ${dayText(last)}` : `${dayText(first)} – ${dayText(last)}`)

// A design's dates: "4 Nov", "4 Nov 2026, 16:20", and how long ago.
const dayOf = (iso: string) => new Date(iso).toLocaleDateString('en-GB', { day: 'numeric', month: 'short' })
const dayAndTimeOf = (iso: string) => {
  const at = new Date(iso)

  return `${at.toLocaleDateString('en-GB', { day: 'numeric', month: 'short', year: 'numeric' })}, ${at.toLocaleTimeString('en-GB', { hour: '2-digit', minute: '2-digit' })}`
}
const agoOf = (at: number, now: number) => {
  const minutes = Math.max(0, Math.round((now - at) / 60_000))
  if (Number.isNaN(minutes) || minutes < 1) return 'just now'
  if (minutes < 60) return `${minutes} min ago`
  if (minutes < 60 * 24) return `${Math.round(minutes / 60)}h ago`

  return `${Math.round(minutes / (60 * 24))} days ago`
}

