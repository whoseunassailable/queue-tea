// What Claude may propose: a message and the repository-relative paths of the
// files to commit. Rohan still picks, edits and commits them in Branches.
export const PROPOSAL_LIMITS = { message: 2_000, files: 500, path: 1_024 } as const

export type ProposalInput = { message: string; files: string[] }
export type ProposalProblem = 'message' | 'credit' | 'files' | 'path'

// Rohan's commits never say who drafted them: no co-author or "generated
// with" lines, no "proposed by Claude". Naming Claude Code as a feature is fine.
const CREDITS = [
  /^\s*co-authored-by:.*(claude|anthropic)/im,
  /noreply@anthropic\.com/i,
  // At a line's start, so "titles generated by Claude" in a subject still passes.
  /^\W*generated (with|by)\b.*\bclaude/im,
  /\b(proposed|written|drafted|authored|created|made|suggested|prepared) (by|with) claude\b/i,
  /\u{1F916}/u,
]

export const creditsClaude = (message: string): boolean => CREDITS.some(credit => credit.test(message))

const isPath = (path: unknown): path is string =>
  typeof path === 'string' &&
  path.trim() === path &&
  path !== '' &&
  path.length <= PROPOSAL_LIMITS.path &&
  !path.includes('\0') &&
  !path.startsWith('/') &&
  !path.split('/').includes('..')

export const checkProposal = (input: unknown): ProposalInput | ProposalProblem => {
  const { message: raw, files } = (input ?? {}) as { message?: unknown; files?: unknown }
  const message = typeof raw === 'string' ? raw.trim() : ''
  if (message === '' || message.length > PROPOSAL_LIMITS.message || message.includes('\0')) return 'message'
  if (creditsClaude(message)) return 'credit'
  if (!Array.isArray(files) || files.length === 0 || files.length > PROPOSAL_LIMITS.files) return 'files'
  if (!files.every(isPath)) return 'path'

  return { message, files: [...new Set(files)] }
}
